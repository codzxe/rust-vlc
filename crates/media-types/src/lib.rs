//! The Lumen shared vocabulary: the explicit type system every other crate
//! speaks (doc 01 §3; MP §8 — explicit types, no sentinel numbers).
//!
//! Layer L0, no internal dependencies, std-only `[PROPOSAL per doc 01
//! §2.2(c)]`. Data types and pure functions only — no I/O, no threading
//! primitives in the public API, no UI/GPU/platform types (ARCH-1), no
//! format-specific parsing. This crate is deliberately boring and
//! extremely stable; it is the most reviewed crate in the repo (doc 01
//! §2.2(a)) and every public item below is part of that review surface.
//!
//! # Module map
//!
//! - [`ids`]   — identity: [`SourceUri`] (validated, redactable), scheme,
//!   stream/track/generation ids, [`MediaKind`], [`Track`] and its
//!   descriptor types (doc 01 §3.1).
//! - [`time`]  — timing: [`TimeBase`], [`Timestamp`] with checked
//!   conversions, [`TimeError`], [`Stamp`], [`TimeSpan`], [`Rate`],
//!   [`Duration`], [`TrackTiming`] (doc 01 §3.2).
//! - [`packet`] — compressed data in flight: [`Packet`], [`SharedBytes`]
//!   (doc 01 §3.3).
//! - [`frame`] — decoded data: audio/video/subtitle frames, sample and
//!   pixel formats, minimal colorimetry (doc 01 §3.3).
//! - [`error`] — the stage-tagged seven-kind error taxonomy, no secrets
//!   (doc 01 §3.4).
//!
//! # Core rules (MP §8, tested throughout)
//!
//! - A value and its absence are different types (`Stamp`, `Duration`) —
//!   never `0`/`-1` sentinels.
//! - Conversion failure is data (`TimeError`), never a panic; all
//!   arithmetic is checked.
//! - Errors name the failing stage, carry structured context, and their
//!   `Display` never embeds credentials or full user paths — URIs appear
//!   only through [`SourceUri::redacted`] (MP §12).
//!
//! [`SourceUri::redacted`]: crate::ids::SourceUri::redacted

