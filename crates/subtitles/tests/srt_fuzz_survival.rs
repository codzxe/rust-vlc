//! Fuzz-lite survival AC (card 5.M1 `+FB`): the committed
//! mutated/truncated corpus (`tests/fixtures/fuzz/`, 37 files /
//! 4.7 KB — well under the 200 KB budget) plus a deterministic
//! seeded mutation loop, all through the [`subtitles::srt::fuzz`]
//! harness (`fuzz_sub_srt`, doc 04 §5 registry).
//!
//! **Contract: absence of panic/hang/unbounded allocation** —
//! mutated input is expected to produce damage events or fewer
//! cues, never a crash, never a mid-file abort of the surviving
//! cues. Pinned invariants per run:
//!
//! * the damage ledger respects its cap (256) with the overflow
//!   *counted*, never stored;
//! * every surviving cue's interval is valid (the model's
//!   constructor invariant — re-checked here as the cross-layer
//!   contract);
//! * cue text is well-formed UTF-8 with no residual markup bytes
//!   (`<`/`>` only from literals, never from un-stripped tags).
//!
//! The corpus is generated by a deterministic script (systematic
//! truncations at 16-byte strides, bit flips at 8/24-byte strides,
//! BOM grafts, CRLF rewrites) over the canonical ffmpeg fixtures —
//! committed, so the survival run is reproducible offline.

use subtitles::srt::{self, damage::MAX_DAMAGE_EVENTS};
use testkit::Must;

const FUZZ_DIR: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/fixtures/fuzz");
const CANONICAL: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/fixtures/canonical");

fn invariants(name: &str, bytes: &[u8]) {
    let doc = srt::parse(bytes);
    assert!(
        doc.damages.len() <= MAX_DAMAGE_EVENTS,
        "{name}: damage ledger over cap ({} > {MAX_DAMAGE_EVENTS})",
        doc.damages.len()
    );
    for cue in &doc.cues {
        assert!(
            cue.interval.start_us() <= cue.interval.end_us(),
            "{name}: invalid interval in a survived cue"
        );
    }
    // Surviving cue count sanity: never more cues than bytes (each
    // cue needs at least a timing line + a text line).
    assert!(
        doc.cues.len() <= bytes.len(),
        "{name}: more cues than bytes"
    );
    // The harness itself (full parse + render path per cue).
    subtitles::srt::fuzz::fuzz_sub_srt(bytes);
}

#[test]
fn committed_corpus_survives() {
    let mut entries: Vec<_> = std::fs::read_dir(FUZZ_DIR)
        .must()
        .map(|e| e.must())
        .collect();
    entries.sort_by_key(|e| e.file_name());
    assert!(
        entries.len() >= 30,
        "committed fuzz corpus shrank: {} files",
        entries.len()
    );
    for entry in &entries {
        let name = entry.file_name().to_string_lossy().into_owned();
        let bytes = std::fs::read(entry.path()).must();
        invariants(&name, &bytes);
    }
}

#[test]
fn canonical_parents_still_parse_exactly() {
    // The mutation parents must be clean before any mutation talk.
    for name in ["out1.srt", "out2.srt", "out3.srt"] {
        let bytes = std::fs::read(format!("{CANONICAL}/{name}")).must();
        let doc = srt::parse(&bytes);
        assert!(doc.is_clean(), "{name}: unexpected damage");
        assert!(!doc.cues.is_empty(), "{name}: no cues");
    }
}

/// xorshift64* — deterministic, std-only.
struct Lcg(u64);

impl Lcg {
    fn next(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }
}

#[test]
fn seeded_mutation_loop_survives() {
    let base = std::fs::read(format!("{CANONICAL}/out2.srt")).must();
    let base16 = std::fs::read(format!("{CANONICAL}/out2-utf16le.srt")).must();
    let mut rng = Lcg(0x5115_0000_0051_4D31);
    for i in 0..2000u32 {
        let parent: &[u8] = if i % 3 == 0 { &base16 } else { &base };
        let mut mutant = parent.to_vec();
        // 1–4 mutations per iteration: byte flips, truncation,
        // insertion of junk, BOM grafts.
        let ops = (rng.next() % 4) as usize + 1;
        for _ in 0..ops {
            if mutant.is_empty() {
                break;
            }
            match rng.next() % 4 {
                0 => {
                    let at = (rng.next() as usize) % mutant.len();
                    mutant[at] ^= 0x80;
                }
                1 => {
                    let at = (rng.next() as usize) % mutant.len();
                    mutant[at] = (rng.next() % 256) as u8;
                }
                2 => {
                    let cut = (rng.next() as usize) % mutant.len();
                    mutant.truncate(cut);
                }
                _ => {
                    let at = (rng.next() as usize) % mutant.len();
                    let junk = [
                        b'\n', b'-', b'>', b',', b':', 0xFF, 0xFE, 0x00, b'<', b'&', 0xD8,
                    ][(rng.next() as usize) % 11];
                    mutant.insert(at, junk);
                }
            }
        }
        invariants(&format!("seeded-{i}"), &mutant);
    }
}

#[test]
fn truncations_never_beat_the_parser() {
    // Every prefix of every canonical parent: parse must terminate
    // with a valid (possibly empty) document.
    for name in ["out1.srt", "out2.srt", "out3.srt", "out3-utf16be.srt"] {
        let bytes = std::fs::read(format!("{CANONICAL}/{name}")).must();
        for cut in 0..=bytes.len() {
            invariants(&format!("{name}@{cut}"), &bytes[..cut]);
        }
    }
}
