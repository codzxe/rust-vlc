/// Little-endian scalar emitters (RIFF is little-endian throughout).
fn put_u16le(out: &mut Vec<u8>, value: u16) {
    out.extend_from_slice(&value.to_le_bytes());
}
fn put_u32le(out: &mut Vec<u8>, value: u32) {
    out.extend_from_slice(&value.to_le_bytes());
}

/// Append one RIFF chunk (`fourcc <u32le size> payload [pad]`).
fn chunk(out: &mut Vec<u8>, fourcc: &[u8; 4], payload: &[u8]) -> usize {
    let offset = out.len();
    out.extend_from_slice(fourcc);
    put_u32le(out, payload.len() as u32);
    out.extend_from_slice(payload);
    if payload.len() & 1 == 1 {
        out.push(0);
    }
    offset
}

/// Open a sized chunk with a zero size placeholder; returns the size
/// field's offset.
fn begin_sized(out: &mut Vec<u8>, fourcc: &[u8; 4]) -> usize {
    out.extend_from_slice(fourcc);
    let size_pos = out.len();
    put_u32le(out, 0);
    size_pos
}

/// Patch the size field opened by [`begin_sized`] (a RIFF/LIST size
/// includes its form FourCC).
fn end_sized(out: &mut [u8], size_pos: usize) {
    let size = out.len() - size_pos - 4;
    out[size_pos..size_pos + 4].copy_from_slice(&(size as u32).to_le_bytes());
}

/// One synthetic audio stream (s16le or u8, mono).
struct SynthAudio {
    data: Vec<u8>,
    rate: u32,
    bits: u16,
}

impl SynthAudio {
    fn frame_bytes(&self) -> usize {
        usize::from(self.bits) / 8
    }
}

/// Build a minimal RIFF/AVI 1.0 file: one `vids` stream (handler
/// `video_fourcc`, e.g. `MJPG` or `mpeg4`) with `frames` dummy frames
/// and `audio.len()` `auds`/PCM streams, one `NNwb` chunk per stream
/// per tick, fully indexed by `idx1` (mirrors the xtask fixture
/// writer's shapes — the same bytes the demuxer's own tests parse).
fn build_synth_avi(
    frames: usize,
    fps: u32,
    audio: &[SynthAudio],
    video_fourcc: &[u8; 4],
) -> Vec<u8> {
    let mut out: Vec<u8> = Vec::new();
    out.extend_from_slice(b"RIFF");
    let riff_size_pos = out.len();
    put_u32le(&mut out, 0);
    out.extend_from_slice(b"AVI ");

    // hdrl
    let hdrl_pos = begin_sized(&mut out, b"LIST");
    out.extend_from_slice(b"hdrl");
    // avih (56 bytes)
    let mut avih = Vec::with_capacity(56);
    put_u32le(&mut avih, 1_000_000 / fps); // dwMicroSecPerFrame
    put_u32le(&mut avih, 0); // dwMaxBytesPerSec
    put_u32le(&mut avih, 0); // dwPaddingGranularity
    put_u32le(&mut avih, 0x0000_0010 | 0x0000_0100); // HASINDEX | ISINTERLEAVED
    put_u32le(&mut avih, frames as u32); // dwTotalFrames
    put_u32le(&mut avih, 0); // dwInitialFrames
    put_u32le(&mut avih, (1 + audio.len()) as u32); // dwStreams
    put_u32le(&mut avih, 4096); // dwSuggestedBufferSize
    put_u32le(&mut avih, 16); // dwWidth
    put_u32le(&mut avih, 16); // dwHeight
    for _ in 0..4 {
        put_u32le(&mut avih, 0);
    }
    chunk(&mut out, b"avih", &avih);

    // strl: video (vids/MJPG, 16×16, 24-bit BITMAPINFOHEADER)
    {
        let pos = begin_sized(&mut out, b"LIST");
        out.extend_from_slice(b"strl");
        let mut strh = Vec::with_capacity(56);
        strh.extend_from_slice(b"vids");
        strh.extend_from_slice(video_fourcc);
        put_u32le(&mut strh, 0); // dwFlags
        put_u16le(&mut strh, 0); // wPriority
        put_u16le(&mut strh, 0); // wLanguage
        put_u32le(&mut strh, 0); // dwInitialFrames
        put_u32le(&mut strh, 1); // dwScale
        put_u32le(&mut strh, fps); // dwRate
        put_u32le(&mut strh, 0); // dwStart
        put_u32le(&mut strh, frames as u32); // dwLength
        put_u32le(&mut strh, 4096); // dwSuggestedBufferSize
        put_u32le(&mut strh, u32::MAX); // dwQuality
        put_u32le(&mut strh, 0); // dwSampleSize
        put_u16le(&mut strh, 0);
        put_u16le(&mut strh, 0);
        put_u16le(&mut strh, 16);
        put_u16le(&mut strh, 16);
        chunk(&mut out, b"strh", &strh);
        let mut strf = Vec::with_capacity(40);
        put_u32le(&mut strf, 40);
        put_u32le(&mut strf, 16);
        put_u32le(&mut strf, 16);
        put_u16le(&mut strf, 1);
        put_u16le(&mut strf, 24);
        strf.extend_from_slice(b"MJPG");
        put_u32le(&mut strf, 16 * 16 * 3);
        put_u32le(&mut strf, 0);
        put_u32le(&mut strf, 0);
        put_u32le(&mut strf, 0);
        put_u32le(&mut strf, 0);
        chunk(&mut out, b"strf", &strf);
        end_sized(&mut out, pos);
    }

    // strl: one per audio stream (auds, PCMWAVEFORMAT strf)
    for stream in audio {
        let pos = begin_sized(&mut out, b"LIST");
        out.extend_from_slice(b"strl");
        let mut strh = Vec::with_capacity(56);
        strh.extend_from_slice(b"auds");
        strh.extend_from_slice(&[0u8; 4]);
        put_u32le(&mut strh, 0);
        put_u16le(&mut strh, 0);
        put_u16le(&mut strh, 0);
        put_u32le(&mut strh, 0);
        put_u32le(&mut strh, 1); // dwScale
        put_u32le(&mut strh, stream.rate); // dwRate
        put_u32le(&mut strh, 0); // dwStart
        put_u32le(&mut strh, (stream.data.len() / stream.frame_bytes()) as u32); // dwLength
        put_u32le(&mut strh, 4096);
        put_u32le(&mut strh, u32::MAX);
        put_u32le(&mut strh, stream.frame_bytes() as u32); // dwSampleSize (block align)
        put_u16le(&mut strh, 0);
        put_u16le(&mut strh, 0);
        put_u16le(&mut strh, 0);
        put_u16le(&mut strh, 0);
        chunk(&mut out, b"strh", &strh);
        let mut strf = Vec::with_capacity(16);
        put_u16le(&mut strf, 1); // WAVE_FORMAT_PCM
        put_u16le(&mut strf, 1); // mono
        put_u32le(&mut strf, stream.rate);
        put_u32le(&mut strf, stream.rate * stream.frame_bytes() as u32);
        put_u16le(&mut strf, stream.frame_bytes() as u16);
        put_u16le(&mut strf, stream.bits);
        chunk(&mut out, b"strf", &strf);
        end_sized(&mut out, pos);
    }
    end_sized(&mut out, hdrl_pos);

    // movi: per tick — 00dc (dummy video payload), then NNwb per
    // audio stream. Chunk offsets recorded for idx1.
    let movi_pos = begin_sized(&mut out, b"LIST");
    out.extend_from_slice(b"movi");
    // `movi_pos` is the SIZE-FIELD position (begin_sized's return);
    // the 'movi' form fourcc sits at movi_pos + 4, and idx1 dwOffsets
    // are relative to that fourcc (the demuxer's probe_offset_base
    // pins the same base — an off-by-four here drops the first entry
    // as `idx1-entry-outside-movi`).
    let movi_fourcc_at = movi_pos + 4;
    let mut index: Vec<([u8; 4], usize, usize)> = Vec::new();
    for tick in 0..frames {
        let offset = chunk(&mut out, b"00dc", &[0x33u8, 0x33, 0x33, 0x33]);
        index.push((*b"00dc", offset, 4));
        for (stream_number, stream) in audio.iter().enumerate() {
            let bytes_per_tick = stream.rate as usize / fps as usize * stream.frame_bytes();
            let start = tick * bytes_per_tick;
            let payload = &stream.data[start..start + bytes_per_tick];
            let fourcc: [u8; 4] = [b'0', b'0' + (stream_number as u8 + 1), b'w', b'b'];
            let offset = chunk(&mut out, &fourcc, payload);
            index.push((fourcc, offset, payload.len()));
        }
    }
    end_sized(&mut out, movi_pos);

    // idx1: every chunk, AVIIF_KEYFRAME, offsets relative to 'movi'.
    let mut idx1 = Vec::new();
    for (fourcc, offset, size) in &index {
        idx1.extend_from_slice(fourcc);
        put_u32le(&mut idx1, 0x10);
        put_u32le(&mut idx1, (offset - movi_fourcc_at) as u32);
        put_u32le(&mut idx1, *size as u32);
    }
    chunk(&mut out, b"idx1", &idx1);

    end_sized(&mut out, riff_size_pos);
    out
}

/// Open a synthetic stream (the input crate's in-memory seam).
fn synth_stream(bytes: &[u8]) -> Box<dyn SourceStream> {
    let stream = SyntheticStream::new(bytes, 4096)
        .unwrap_or_else(|err| unreachable!("synthetic stream must build: {err}"));
    Box::new(stream)
}

#[test]
fn synthetic_avi_digest_is_exactly_first_track_pcm() {
    // Two audio streams with distinct, known PCM. Track 1 (01wb):
    // s16le counter pattern; track 2 (02wb): 0xAA fill — the digest
    // must be track 1's bytes and NOTHING else (no video payload, no
    // track-2 leakage, no container bytes).
    let rate = 800u32;
    let fps = 8u32;
    let frames = 2usize;
    let samples_per_tick = (rate / fps) as usize; // 100
    let mut first = Vec::new();
    let mut second = Vec::new();
    for i in 0..frames * samples_per_tick {
        first.extend_from_slice(&((i as u16) % 4096).to_le_bytes());
        second.extend_from_slice(&[0xAAu8, 0x2A]);
    }
    let audio = [
        SynthAudio {
            data: first.clone(),
            rate,
            bits: 16,
        },
        SynthAudio {
            data: second,
            rate,
            bits: 16,
        },
    ];
    let bytes = build_synth_avi(frames, fps, &audio, b"MJPG");
    let report = digest_avi_first_pcm_audio_from(synth_stream(&bytes))
        .unwrap_or_else(|err| unreachable!("synthetic AVI must digest: {err}"));
    assert_eq!(report.codec, "pcm_s16le");
    assert_eq!(report.channels, 1);
    assert_eq!(report.rate, rate);
    assert_eq!(report.track_handle, 1, "the FIRST audio stream");
    assert_eq!(report.pcm_bytes, first.len() as u64);
    assert_eq!(report.packets, frames as u64, "one packet per tick");
    assert_eq!(report.concealed, 0);
    assert_eq!(report.demux_recovered, 0, "MJPG video is never filtered");
    assert_eq!(report.demux_skip_bytes, 0);
    assert_eq!(
        report.md5_hex,
        md5_hex(&first),
        "digest == MD5 of track-1 PCM bytes alone"
    );
}

#[test]
fn filtered_video_stream_does_not_touch_the_audio_digest() {
    // The v0 codec filter refuses non-MJPEG video handlers at start
    // and records one `Recovered` DECISION per filtered stream
    // (skipped == 0 — W5-14's disposition records). The audio digest
    // must be exactly the audio track's PCM: the corpus's mpeg4-video
    // AVIs with PCM audio ride this path (media/0040-avi-av.avi and
    // friends), so it is pinned here on a synthetic file.
    let rate = 800u32;
    let fps = 8u32;
    let frames = 2usize;
    let samples_per_tick = (rate / fps) as usize;
    let mut first = Vec::new();
    for i in 0..frames * samples_per_tick {
        first.extend_from_slice(&((i as u16) % 4096).to_le_bytes());
    }
    let audio = [SynthAudio {
        data: first.clone(),
        rate,
        bits: 16,
    }];
    let bytes = build_synth_avi(frames, fps, &audio, b"FMP4");
    let report = digest_avi_first_pcm_audio_from(synth_stream(&bytes))
        .unwrap_or_else(|err| unreachable!("filtered-video AVI must digest: {err}"));
    assert_eq!(report.codec, "pcm_s16le");
    assert_eq!(report.track_handle, 1);
    assert_eq!(report.pcm_bytes, first.len() as u64);
    assert_eq!(report.concealed, 0);
    assert_eq!(
        report.demux_recovered, 2,
        "two Recovered events on this build: the filter decision \
         (unsupported-video-handler, skipped 0) + the filtered stream's \
         idx1 entries dropping as idx1-entry-unknown-stream (16 B each — \
         W5-14's pending merge silences the latter)"
    );
    assert_eq!(
        report.demux_skip_bytes, 32,
        "2 video idx1 entries x 16 B — seek-table drops, not walked data"
    );
    assert_eq!(
        report.md5_hex,
        md5_hex(&first),
        "the filtered video stream leaves the audio digest untouched"
    );
}

#[test]
fn synthetic_avi_u8_family_digests() {
    // The u8 family (the other afile-representable pin).
    let rate = 800u32;
    let fps = 8u32;
    let frames = 3usize;
    let per_tick = (rate / fps) as usize;
    let data: Vec<u8> = (0..frames * per_tick)
        .map(|i| (i * 5 % 251) as u8)
        .collect();
    let audio = [SynthAudio {
        data: data.clone(),
        rate,
        bits: 8,
    }];
    let bytes = build_synth_avi(frames, fps, &audio, b"MJPG");
    let report = digest_avi_first_pcm_audio_from(synth_stream(&bytes))
        .unwrap_or_else(|err| unreachable!("synthetic AVI must digest: {err}"));
    assert_eq!(report.codec, "pcm_u8");
    assert_eq!(report.sample, "u8");
    assert_eq!(report.pcm_bytes, data.len() as u64);
    assert_eq!(report.demux_recovered, 0);
    assert_eq!(report.demux_skip_bytes, 0);
    assert_eq!(report.md5_hex, md5_hex(&data));
}

#[test]
fn synthetic_frames_feed_the_sink_in_order() {
    // The sink layer directly: three synthetic audio frames whose
    // concatenation's MD5 must equal the sink's digest (order and
    // completeness — the property the harness's comparison stands on).
    use bench_vs_vlc::DigestSink;
    use codec_api::FrameSink;
    use media_types::frame::{AudioFrame, AudioLayout, SampleFormat};
    use media_types::{AudioFormat, Frame, Stamp};

    let format = AudioFormat {
        sample: SampleFormat::S16,
        channels: 1,
        layout: AudioLayout::Interleaved,
        rate: 8000,
    };
    let payloads: Vec<Vec<u8>> = (0..3)
        .map(|frame| (0..64u16).map(|i| (frame * 64 + i) as u8).collect())
        .collect();
    let mut sink = DigestSink::new();
    for payload in &payloads {
        sink.accept(Frame::Audio(AudioFrame {
            format,
            samples: SharedBytes::from_vec(payload.clone()),
            pts: Stamp::Missing,
            duration: None,
            generation: media_types::GenerationId::FIRST,
        }))
        .unwrap_or_else(|err| unreachable!("sink must accept: {err}"));
    }
    let joined: Vec<u8> = payloads.concat();
    assert_eq!(sink.frames, 3);
    assert_eq!(sink.bytes, joined.len() as u64);
    assert_eq!(sink.other_kinds, 0);
    assert_eq!(sink.format, Some(format));
    assert_eq!(sink.digest_hex(), md5_hex(&joined));
}

