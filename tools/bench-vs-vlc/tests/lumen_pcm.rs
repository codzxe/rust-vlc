#[test]
fn batch_json_envelope_carries_rows_and_host_endian() {
    let fixtures = vec![(
        "fixture:avi_mjpeg_pcm.avi".to_string(),
        fixture("generated/valid/avi_mjpeg_pcm.avi"),
    )];
    let outcomes = digest_batch(&fixtures);
    let json = render_batch_json(&outcomes);
    assert!(json.contains("\"schema\": \"bench-vs-vlc/lumen-pcm-digests/1\""));
    assert!(json.contains(&format!("\"host_endian\": \"{}\"", host_endian())));
    assert!(json.contains("\"rel\": \"fixture:avi_mjpeg_pcm.avi\""));
    assert!(json.contains("\"status\": \"ok\""));
    // A 32-hex md5 field is present (scan for the key, then hex run).
    let at = json.find("\"md5\": \"").map(|position| position + 8);
    let Some(at) = at else {
        unreachable!("the envelope must carry an md5 field: {json}");
    };
    let hex: String = json[at..]
        .chars()
        .take_while(|c| c.is_ascii_hexdigit())
        .collect();
    assert_eq!(hex.len(), 32, "md5 is 32 lowercase hex chars: {json}");
}

/// The batch entry the Python orchestrator drives:
///
/// ```text
/// LUMEN_DIFF_FIXTURES=<tsv> LUMEN_DIFF_OUT=<json> \
///     cargo test --test lumen_pcm -- --ignored --nocapture
/// ```
///
/// Not part of a plain `cargo test` run (it needs the orchestrator's
/// fixture list); when driven, it MUST answer every requested fixture
/// — one row per rel, no silent skips.
#[test]
#[ignore = "driven by tools/bench-vs-vlc/run.py via LUMEN_DIFF_FIXTURES/LUMEN_DIFF_OUT"]
fn corpus_batch_via_env() {
    let fixtures_path = std::env::var("LUMEN_DIFF_FIXTURES").unwrap_or_default();
    let out_path = std::env::var("LUMEN_DIFF_OUT").unwrap_or_default();
    assert!(
        !fixtures_path.is_empty() && !out_path.is_empty(),
        "corpus_batch_via_env requires LUMEN_DIFF_FIXTURES and LUMEN_DIFF_OUT (drive via run.py)"
    );
    let text = std::fs::read_to_string(&fixtures_path)
        .unwrap_or_else(|err| unreachable!("fixtures list must be readable: {err}"));
    let fixtures = parse_fixture_tsv(&text)
        .unwrap_or_else(|err| unreachable!("fixtures list must parse: {err}"));
    assert!(
        !fixtures.is_empty(),
        "the orchestrator never sends an empty batch"
    );
    let outcomes = digest_batch(&fixtures);
    assert_eq!(
        outcomes.len(),
        fixtures.len(),
        "one row per fixture, no skips"
    );
    let json = render_batch_json(&outcomes);
    for (rel, _) in &fixtures {
        let needle = format!("\"rel\": \"{}\"", rel);
        assert!(json.contains(&needle), "row for {rel} missing");
    }
    std::fs::write(&out_path, json)
        .unwrap_or_else(|err| unreachable!("results file must be writable: {err}"));
}
