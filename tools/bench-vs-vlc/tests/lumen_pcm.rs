#[test]
fn garbage_file_is_a_typed_refusal() {
    let garbage = std::env::temp_dir().join("bench-vs-vlc-garbage.bin");
    std::fs::write(&garbage, [0x37u8, 0x13, 0x00, 0x42, 0xff, 0xee].repeat(64)).unwrap_or_default();
    let outcome = digest_avi_first_pcm_audio(&garbage);
    std::fs::remove_file(&garbage).ok();
    let Err(error) = outcome else {
        unreachable!("garbage must refuse, never digest");
    };
    assert!(
        error.starts_with("[probe]") || error.starts_with("[input]"),
        "typed stage-tagged refusal, got: {error}"
    );
}

