//! Integration tests — the Lumen side of the differential-vs-VLC
//! harness (card 3.E3, doc 10 §6.6).
//!
//! Two layers:
//!
//! 1. **Always-on** unit/integration tests: the committed class-A
//!    fixtures' digests are PINNED (regression pins — a decode change
//!    that alters decoded PCM must fail here first), the synthetic
//!    in-memory AVIs prove the first-audio-track digest is exactly the
//!    first track's PCM bytes (the acceptance's "digest logic tested
//!    on synthetic PCM"), and garbage input is a typed refusal.
//! 2. **`corpus_batch_via_env`** (marked `#[ignore]`): the batch entry
//!    `run.py` drives over real corpus fixtures via
//!    `LUMEN_DIFF_FIXTURES` (TSV) / `LUMEN_DIFF_OUT` (JSON). Ignored
//!    by default so it never silently no-ops a plain `cargo test` —
//!    the orchestrator runs it explicitly and it asserts it produced
//!    a row for every requested fixture.

