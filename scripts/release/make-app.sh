#!/bin/sh
# make-app.sh — construct the macOS application bundle (<Name>.app) from
# the product config environment (card 7.w22g, issue #56 release half).
#
# Bundle layout (Apple's documented macOS bundle structure):
#   <Name>.app/
#     Contents/Info.plist          (generated; fields from product.toml)
#     Contents/MacOS/<desktop bin> (the lumen-desktop binary)
#     Contents/Resources/LICENSE
#     Contents/Resources/README.md
#
# Config-driven Info.plist fields (via scripts/release/product-env.py):
#   CFBundleName              <- identity.name
#   CFBundleDisplayName       <- identity.name
#   CFBundleIdentifier        <- identity.ids.macos.bundle_id
#   CFBundleShortVersionString<- identity.display_version
#   CFBundleVersion           <- identity.version_code (monotonic integer)
#   CFBundleExecutable        <- the desktop package's [[bin]] name
#
# HONEST LIMIT (issue #56, docs/RELEASE.md): the bundle is NOT code
# signed and NOT notarized — no Apple Developer account exists for this
# project. Gatekeeper will quarantine a downloaded bundle; users bypass
# via right-click > Open (README "Install" documents this). Note the
# aarch64 binary itself carries the linker's default ad-hoc signature
# (rustc/ld behavior on arm64-apple-darwin), which is not a Developer ID.
#
# Pure file operations — runs on any POSIX host (layout verifiable on
# Linux; the release workflow runs it on macOS).
#
# Usage: make-app.sh
# POSIX sh; `bash -n` clean.

set -eu

: "${PRODUCT_NAME:?make-app.sh: PRODUCT_NAME not set}"
: "${PRODUCT_VERSION:?make-app.sh: PRODUCT_VERSION not set}"
: "${PRODUCT_VERSION_CODE:?make-app.sh: PRODUCT_VERSION_CODE not set}"
: "${PRODUCT_BUNDLE_ID:?make-app.sh: PRODUCT_BUNDLE_ID not set}"
: "${BIN_DESKTOP:?make-app.sh: BIN_DESKTOP not set}"
TARGET_DIR=${TARGET_DIR:-target}
DIST_DIR=${DIST_DIR:-dist}
APP_DIR=${APP_DIR:-$DIST_DIR}

ROOT=$(cd "$(dirname -- "$0")/../.." && pwd)
cd "$ROOT"

die() { echo "make-app.sh: error: $*" >&2; exit 2; }

bin="$TARGET_DIR/release/$BIN_DESKTOP"
[ -f "$bin" ] || die "missing desktop binary: $bin (build first: cargo build --release --locked)"
[ -f LICENSE ] && [ -f README.md ] || die "LICENSE/README.md not found in repo root"

app_root="$APP_DIR/${PRODUCT_NAME}.app"
mkdir -p "$app_root/Contents/MacOS" "$app_root/Contents/Resources"

install -m 0755 "$bin" "$app_root/Contents/MacOS/$BIN_DESKTOP"
cp LICENSE README.md "$app_root/Contents/Resources/"

xml_escape() {
    printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' \
        -e 's/>/\&gt;/g' -e 's/"/\&quot;/g'
}

esc_name=$(xml_escape "$PRODUCT_NAME")
esc_bundle_id=$(xml_escape "$PRODUCT_BUNDLE_ID")

cat >"$app_root/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<!-- Generated by scripts/release/make-app.sh — DO NOT HAND-EDIT.
     Every identity field comes from product.toml (via product-env.py);
     regenerate instead of editing (MP §5). -->
<dict>
    <key>CFBundleName</key>
    <string>${esc_name}</string>
    <key>CFBundleDisplayName</key>
    <string>${esc_name}</string>
    <key>CFBundleIdentifier</key>
    <string>${esc_bundle_id}</string>
    <key>CFBundleVersion</key>
    <string>${PRODUCT_VERSION_CODE}</string>
    <key>CFBundleShortVersionString</key>
    <string>${PRODUCT_VERSION}</string>
    <key>CFBundleExecutable</key>
    <string>${BIN_DESKTOP}</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleInfoDictionaryVersion</key>
    <string>6.0</string>
    <key>LSMinimumSystemVersion</key>
    <string>11.0</string>
    <key>NSHighResolutionCapable</key>
    <true/>
    <key>LSApplicationCategoryType</key>
    <string>public.app-category.entertainment</string>
</dict>
</plist>
EOF

echo "make-app.sh: wrote $app_root (bundle id=${esc_bundle_id} version=${PRODUCT_VERSION} build=${PRODUCT_VERSION_CODE})"
