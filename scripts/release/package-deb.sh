#!/bin/sh
# package-deb.sh — build the Debian package with the NATIVE dpkg-deb
# (card 7.w22g, issue #56 release half).
#
# No third-party tooling (no cargo-deb, no fpm): a classic staging tree
#   root/DEBIAN/control
#   root/usr/bin/<cli bin> <desktop bin>
#   root/usr/share/doc/<slug>/{LICENSE,README.md}
#   root/usr/share/applications/<appstream id>.desktop
#   root/usr/share/icons/hicolor/512x512/apps/<slug>.png
# packed with `dpkg-deb --root-owner-group --build`.
#
# Every metadata field is config-driven (via scripts/release/
# product-env.py):
#   Package     <- identity.name slugified (PRODUCT_LOWER)
#   Version     <- identity.display_version (pre-release suffixes such
#                  as "-dev" are valid in Debian version syntax)
#   Maintainer  <- identity.publisher
#   Description <- locales/<default locale>.toml, key identity.description_key
#   desktop file Name/Icon <- identity.name / slug
#   Architecture<- mapped from ARCH_ID (x86_64->amd64, aarch64->arm64)
#
# No maintainer scripts (postinst & co.): the package ships only files
# — nothing to trigger. Desktop-entry caches refresh lazily; forcing a
# dependency on desktop-file-utils for one optional cache refresh is
# not worth it.
#
# Icons: assets/brand/*.png do not exist yet (see docs/RELEASE.md known
# limits), so a deterministic placeholder PNG filled with brand
# accent_color is generated by scripts/release/gen-icon.py. Honest and
# clean-room: no borrowed third-party artwork.
#
# Usage: package-deb.sh
# POSIX sh; `bash -n` clean; dry-run tested on Linux (worklog 7.w22g).

set -eu

: "${PRODUCT_LOWER:?package-deb.sh: PRODUCT_LOWER not set}"
: "${PRODUCT_VERSION:?package-deb.sh: PRODUCT_VERSION not set}"
: "${PRODUCT_PUBLISHER:?package-deb.sh: PRODUCT_PUBLISHER not set}"
: "${PRODUCT_DESCRIPTION:?package-deb.sh: PRODUCT_DESCRIPTION not set}"
: "${PRODUCT_NAME:?package-deb.sh: PRODUCT_NAME not set}"
: "${PRODUCT_APPSTREAM_ID:?package-deb.sh: PRODUCT_APPSTREAM_ID not set}"
: "${PRODUCT_ACCENT_COLOR:?package-deb.sh: PRODUCT_ACCENT_COLOR not set}"
: "${BIN_CLI:?package-deb.sh: BIN_CLI not set}"
: "${BIN_DESKTOP:?package-deb.sh: BIN_DESKTOP not set}"
: "${OS_ID:?package-deb.sh: OS_ID not set}"
: "${ARCH_ID:?package-deb.sh: ARCH_ID not set}"
TARGET_DIR=${TARGET_DIR:-target}
DIST_DIR=${DIST_DIR:-dist}

ROOT=$(cd "$(dirname -- "$0")/../.." && pwd)
cd "$ROOT"

die() { echo "package-deb.sh: error: $*" >&2; exit 2; }

command -v dpkg-deb >/dev/null 2>&1 ||
    die "dpkg-deb not found — package-deb.sh needs a Debian-family host"

case "$ARCH_ID" in
    x86_64) deb_arch=amd64 ;;
    aarch64) deb_arch=arm64 ;;
    *) die "cannot map ARCH_ID=${ARCH_ID} to a Debian architecture" ;;
esac

PY=$(command -v python3 || command -v python) ||
    die "neither python3 nor python found on PATH (icon generation needs the stdlib)"

cli_bin="$TARGET_DIR/release/$BIN_CLI"
desktop_bin="$TARGET_DIR/release/$BIN_DESKTOP"
for f in "$cli_bin" "$desktop_bin" LICENSE README.md; do
    [ -f "$f" ] || die "missing packaging input: $f (build first: cargo build --release --locked)"
done

stage=$(mktemp -d)
trap 'rm -rf "$stage"' EXIT INT TERM
root="$stage/root"
docdir="$root/usr/share/doc/$PRODUCT_LOWER"
appsdir="$root/usr/share/applications"
icondir="$root/usr/share/icons/hicolor/512x512/apps"

mkdir -p "$root/DEBIAN" "$root/usr/bin" "$docdir" "$appsdir" "$icondir"

install -m 0755 "$cli_bin" "$root/usr/bin/$BIN_CLI"
install -m 0755 "$desktop_bin" "$root/usr/bin/$BIN_DESKTOP"
cp LICENSE README.md "$docdir/"
# Normalize doc/entry modes: `cp` inherits the caller's umask, which
# would make packaging output depend on who ran the script.
chmod 0644 "$docdir/LICENSE" "$docdir/README.md"

# Desktop entry for the desktop binary (config-driven Name/Icon; the
# Exec key is the installed bin name, per the desktop-entry spec).
cat >"$appsdir/${PRODUCT_APPSTREAM_ID}.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=${PRODUCT_NAME}
Comment=${PRODUCT_DESCRIPTION}
Exec=${BIN_DESKTOP}
Icon=${PRODUCT_LOWER}
Terminal=false
Categories=AudioVideo;Video;Player;
EOF

"$ROOT/scripts/release/gen-icon.py" "$icondir/$PRODUCT_LOWER.png" "$PRODUCT_ACCENT_COLOR"
chmod 0644 "$appsdir/${PRODUCT_APPSTREAM_ID}.desktop" "$icondir/$PRODUCT_LOWER.png"

cat >"$root/DEBIAN/control" <<EOF
Package: ${PRODUCT_LOWER}
Version: ${PRODUCT_VERSION}
Section: video
Priority: optional
Architecture: ${deb_arch}
Maintainer: ${PRODUCT_PUBLISHER}
Description: ${PRODUCT_DESCRIPTION}
 Both shipped binaries (the engine-driven CLI and the desktop
 composition-root binary) install under /usr/bin; this package ships
 files only, no maintainer scripts.
EOF

mkdir -p "$DIST_DIR"
dist_abs=$(cd "$DIST_DIR" && pwd)
out="$dist_abs/${PRODUCT_LOWER}-${PRODUCT_VERSION}-${ARCH_ID}-${OS_ID}.deb"

dpkg-deb --root-owner-group --build "$root" "$out"
[ -s "$out" ] || die "deb is missing or empty: $out"
echo "package-deb.sh: wrote $out (arch=${deb_arch})"
