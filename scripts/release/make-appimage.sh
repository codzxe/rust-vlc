#!/bin/sh
# make-appimage.sh — build the .AppImage with the PINNED appimagetool
# (card 7.w22g, issue #56 release half).
#
# AppDir layout (AppImage spec):
#   AppDir/AppRun                (generated minimal launcher, POSIX sh)
#   AppDir/usr/bin/<desktop bin> (the lumen-desktop binary)
#   AppDir/<slug>.desktop        (Name/Icon config-driven from product.toml)
#   AppDir/<slug>.png + .DirIcon (deterministic placeholder icon —
#                                 assets/brand/*.png do not exist yet;
#                                 see docs/RELEASE.md known limits)
#
# The workflow downloads appimagetool 1.9.1 from the AppImage/appimagetool
# GitHub release (URL + SHA-256 pinned IN THE WORKFLOW, mirroring the
# cargo-deny pin style of ci.yml) and passes its path as APPIMAGETOOL.
# appimagetool itself is an AppImage: APPIMAGE_EXTRACT_AND_RUN=1 runs it
# without FUSE, which hosted runners do not guarantee (ubuntu-24.04
# dropped libfuse2 from the default image).
#
# Usage: make-appimage.sh
# POSIX sh; `bash -n` clean; AppDir construction + full AppImage build
# executed locally on linux x86_64 (worklog 7.w22g).

set -eu

: "${PRODUCT_NAME:?make-appimage.sh: PRODUCT_NAME not set}"
: "${PRODUCT_LOWER:?make-appimage.sh: PRODUCT_LOWER not set}"
: "${PRODUCT_DESCRIPTION:?make-appimage.sh: PRODUCT_DESCRIPTION not set}"
: "${PRODUCT_APPSTREAM_ID:?make-appimage.sh: PRODUCT_APPSTREAM_ID not set}"
: "${PRODUCT_ACCENT_COLOR:?make-appimage.sh: PRODUCT_ACCENT_COLOR not set}"
: "${BIN_DESKTOP:?make-appimage.sh: BIN_DESKTOP not set}"
: "${OS_ID:?make-appimage.sh: OS_ID not set}"
: "${ARCH_ID:?make-appimage.sh: ARCH_ID not set}"
: "${APPIMAGETOOL:?make-appimage.sh: APPIMAGETOOL not set (path to the pinned appimagetool download)}"
TARGET_DIR=${TARGET_DIR:-target}
DIST_DIR=${DIST_DIR:-dist}

ROOT=$(cd "$(dirname -- "$0")/../.." && pwd)
cd "$ROOT"

die() { echo "make-appimage.sh: error: $*" >&2; exit 2; }

[ -x "$APPIMAGETOOL" ] || die "APPIMAGETOOL is not executable: $APPIMAGETOOL"

PY=$(command -v python3 || command -v python) ||
    die "neither python3 nor python found on PATH (icon generation needs the stdlib)"

bin="$TARGET_DIR/release/$BIN_DESKTOP"
[ -f "$bin" ] || die "missing desktop binary: $bin (build first: cargo build --release --locked)"

stage=$(mktemp -d)
trap 'rm -rf "$stage"' EXIT INT TERM
appdir="$stage/AppDir"
mkdir -p "$appdir/usr/bin"

install -m 0755 "$bin" "$appdir/usr/bin/$BIN_DESKTOP"

# Minimal AppRun: exec the bundled binary with the AppDir-relative path.
# $BIN_DESKTOP is substituted at BUILD time (it is the desktop package's
# [[bin]] name from cargo metadata, not a runtime value).
cat >"$appdir/AppRun" <<EOF
#!/bin/sh
# Generated by scripts/release/make-appimage.sh — DO NOT HAND-EDIT.
HERE=\$(dirname "\$0")
exec "\$HERE/usr/bin/${BIN_DESKTOP}" "\$@"
EOF
chmod 0755 "$appdir/AppRun"

# Desktop entry: Type/Name/Comment/Exec/Icon from the product config env.
cat >"$appdir/$PRODUCT_LOWER.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=${PRODUCT_NAME}
Comment=${PRODUCT_DESCRIPTION}
Exec=${BIN_DESKTOP}
Icon=${PRODUCT_LOWER}
Terminal=false
Categories=AudioVideo;Video;Player;
EOF

"$ROOT/scripts/release/gen-icon.py" "$appdir/$PRODUCT_LOWER.png" "$PRODUCT_ACCENT_COLOR"
ln -s "$PRODUCT_LOWER.png" "$appdir/.DirIcon"

mkdir -p "$DIST_DIR"
dist_abs=$(cd "$DIST_DIR" && pwd)
out="$dist_abs/${PRODUCT_LOWER}-${PRODUCT_VERSION:?}-${ARCH_ID}-${OS_ID}.AppImage"

# APPIMAGE_EXTRACT_AND_RUN=1: no FUSE needed on the build host
# (hosted runners ship without a usable /dev/fuse).
APPIMAGE_EXTRACT_AND_RUN=1 "$APPIMAGETOOL" "$appdir" "$out"
[ -s "$out" ] || die "AppImage is missing or empty: $out"
echo "make-appimage.sh: wrote $out"
