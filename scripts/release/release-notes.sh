#!/bin/sh
# release-notes.sh — generate the GitHub Release notes for a tag
# (card 7.w22g, issue #56 release half).
#
# Content: product name + version (config-driven via product-env.py),
# the git log since the previous tag, and pointers to the release
# process doc (docs/RELEASE.md) and the checksum manifest. The prose
# skeleton mirrors the "Release notes template" section of
# docs/RELEASE.md — edit there, not here, when the template changes.
#
# Inputs (environment):
#   PRODUCT_NAME, PRODUCT_VERSION   (product.toml identity)
#   TAG  (optional — defaults to $GITHUB_REF_NAME; when neither is set,
#         a dispatch-mode dry-run header is emitted instead)
#
# Usage: release-notes.sh <output.md>
# POSIX sh; `bash -n` clean; tested locally (worklog 7.w22g).

set -eu

: "${PRODUCT_NAME:?release-notes.sh: PRODUCT_NAME not set}"
: "${PRODUCT_VERSION:?release-notes.sh: PRODUCT_VERSION not set}"

[ $# -eq 1 ] || { echo "usage: $0 <output.md>" >&2; exit 2; }
out=$1

ROOT=$(cd "$(dirname -- "$0")/../.." && pwd)
cd "$ROOT"

tag=${TAG:-${GITHUB_REF_NAME:-}}

if [ -n "$tag" ]; then
    # Previous tag reachable from this one; empty on the first release.
    prev=$(git describe --tags --abbrev=0 "${tag}^" 2>/dev/null || true)
    if [ -n "$prev" ]; then
        range="${prev}..${tag}"
        since="since ${prev}"
        git log --oneline --no-decorate "$range" >"${out}.log" ||
            { echo "release-notes.sh: git log ${range} failed" >&2; exit 1; }
    else
        # First tagged release (or no ancestor tag): last 50 commits.
        range="${tag}"
        since="(first tagged release)"
        git log --oneline --no-decorate -50 "$tag" >"${out}.log" ||
            { echo "release-notes.sh: git log ${tag} failed" >&2; exit 1; }
    fi
else
    range="HEAD"
    since="(workflow_dispatch dry-run — no tag ref)"
    git log --oneline --no-decorate -20 >"${out}.log" ||
        { echo "release-notes.sh: git log failed" >&2; exit 1; }
fi

{
    echo "# ${PRODUCT_NAME} ${PRODUCT_VERSION}"
    echo
    if [ -n "$tag" ]; then
        echo "Release tag: \`${tag}\`"
    else
        echo "Draft notes generated without a tag ref (\`workflow_dispatch\` dry-run)."
    fi
    echo
    echo "## Changes ${since}"
    echo
    if [ -s "${out}.log" ]; then
        # Bullet-prefix every `git log --oneline` line: consecutive bare
        # lines would collapse into one paragraph in rendered Markdown.
        sed 's/^/- /' "${out}.log"
    else
        echo "- (no commits found in range \`${range}\`)"
    fi
    echo
    echo "## Install"
    echo
    echo "Per-OS install instructions: the Install section of the repository README."
    echo
    echo "## Checksums"
    echo
    echo "Verify downloads against the \`SHA256SUMS.txt\` asset:"
    echo '```sh'
    echo 'sha256sum --check SHA256SUMS.txt'
    echo '```'
    echo
    echo "## Known limits (honest)"
    echo
    echo "- Binaries are unsigned: no Windows code-signing certificate, no Apple"
    echo "  Developer ID / notarization (external blockers tracked in issue #56)."
    echo "- Linux arm64 artifacts are best-effort (arm64 hosted-runner availability"
    echo "  varies; see docs/RELEASE.md)."
    echo "- The desktop binary is the ADR-004 std-only composition-root skeleton;"
    echo "  the CLI is the real engine surface in this release."
    echo
    echo "---"
    echo "Generated by \`scripts/release/release-notes.sh\` from the"
    echo "\`docs/RELEASE.md\` template. Process: \`docs/RELEASE.md\`."
} >"$out"

rm -f "${out}.log"
echo "release-notes.sh: wrote $out (tag=${tag:-<none>} range=${range})"
