#!/usr/bin/env bash
# T25 - fuzz campaign over the repo's real targets (cargo-fuzz + sanitizers).
#
# The repo ships 35 fuzz targets with seeds, and this campaign IS wired into a
# gate: .github/workflows/audit.yml's nightly `fuzz` job runs it in 5 shards,
# and this script's exit code fails that job. (The old header line "wires
# none of them into a gate" was written before that job landed and had gone
# stale; corrected with the fail-closed rework below.)
#
# Fail-closed contract (fix F2.3 / F0.5, audit W17-A06 F-001: the campaign used
# to exit 0 even when every target failed to build — a "successful" campaign
# that had fuzzed nothing). ANY of these makes the script exit 1:
#   - cargo-fuzz absent: the CI installs it one step before this script runs,
#     so on a lane absence means the lane is broken — an absent campaign is a
#     red campaign, never a green skip
#   - empty target set: nothing under fuzz/fuzz_targets/ (or no targets
#     passed) — an empty campaign never passes vacuously
#   - a target with no [[bin]] registration in fuzz/Cargo.toml (W17-A06 F-003:
#     a stray .rs file used to die at run time and be labeled "clean")
#   - a run failure: `cargo fuzz run` exits non-zero with no crash artifacts —
#     a build failure or instrument error is NOT "clean"
#   - unrecordable evidence: the summary path cannot be written
# A crash artifact is a permanent regression case (fuzz/corpus/<target>/) and
# is always red. A single green exit exists: EVERY target ran to a clean exit
# (rc=0, no crash artifacts).
#
# Evidence: docs/audit/fuzz-campaign/summary.txt — a COMMITTED path (only
# docs/audit/reports/ is gitignored), date/host-stamped (W17-A06 F-002),
# written by this script alone (never hand-edit). Per-target logs and crash
# artifacts also land in docs/audit/reports/fuzz/campaign/ (the gitignored
# reports tree; CI uploads it as workflow artifacts).
#
# Usage: 25_fuzz_campaign.sh [seconds-per-target] [target ...]
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

RPT="$OUT/fuzz/campaign"            # gitignored reports tree (CI artifact)
EVIDENCE_DIR="$ROOT/docs/audit/fuzz-campaign"
EVIDENCE="$EVIDENCE_DIR/summary.txt"

mkdir -p "$RPT"

SECS="${1:-60}"; shift || true
if [ "$#" -gt 0 ]; then TARGETS=("$@"); else
  mapfile -t TARGETS < <(find fuzz/fuzz_targets -maxdepth 1 -type f -name '*.rs' -printf '%f\n' 2>/dev/null | sed 's/\.rs$//' | sort)
fi

head1 "25. fuzz campaign: ${#TARGETS[@]} target(s) x ${SECS}s"

# --- evidence must be recordable before any verdict can be claimed ---------
# (fix F2.3: a campaign whose summary cannot be written must not be able to
# claim green. Both probes below are checked; every later line goes through
# ev(), which dies the same way.)
if ! mkdir -p "$EVIDENCE_DIR" 2>/dev/null || [ ! -d "$EVIDENCE_DIR" ]; then
  say "GATE FAILED: cannot create evidence directory $EVIDENCE_DIR"
  say "(unrecordable evidence is a red campaign — no green verdict without a summary)"
  exit 1
fi
ev() { # ev <line> — append one line to the committed summary, or die red
  printf '%s\n' "$1" >> "$EVIDENCE" || {
    say "GATE FAILED: cannot write campaign evidence $EVIDENCE"
    exit 1
  }
}
if ! : > "$EVIDENCE" 2>/dev/null; then
  say "GATE FAILED: cannot write campaign evidence $EVIDENCE"
  exit 1
fi
ev "# fuzz campaign evidence - GENERATED by scripts/quality/25_fuzz_campaign.sh"
ev "# (never hand-edit; regenerate: bash scripts/quality/25_fuzz_campaign.sh [secs] [target ...])"
ev "date       : $(stamp)"
ev "host       : $(uname -s -m -r 2>/dev/null || uname -s)"
ev "targets    : ${#TARGETS[@]}"
ev "secs/target: $SECS"
ev "evidence   : docs/audit/fuzz-campaign/summary.txt (committed path)"

if ! need cargo-fuzz; then
  say "install: cargo install --locked cargo-fuzz  (needs nightly for -Zsanitizer)"
  ev "cargo-fuzz : ABSENT (command -v cargo-fuzz found nothing)"
  ev "verdict    : RED - cargo-fuzz absent: the campaign cannot run, and a gate"
  ev "              that cannot run fails (an absent campaign never skips green)."
  ev "fix        : cargo install --locked cargo-fuzz (needs a nightly toolchain)"
  exit 1
fi

if [ "${#TARGETS[@]}" -eq 0 ] || [ -z "${TARGETS[0]:-}" ]; then
  say "GATE FAILED: no targets under fuzz/fuzz_targets/ (an empty target set is an empty campaign - it never passes vacuously)"
  ev "verdict    : RED - empty target set: nothing under fuzz/fuzz_targets/"
  exit 1
fi

# --- every target must be a registered [[bin]] (W17-A06 F-003) -------------
mapfile -t REGISTERED < <(awk '
  /^\[\[bin\]\]/ { inbin = 1; next }
  inbin && /^name[[:space:]]*=/ { gsub(/[" ]/, "", $3); print $3; inbin = 0 }
' fuzz/Cargo.toml 2>/dev/null | sort)
UNREGISTERED=()
for t in "${TARGETS[@]}"; do
  found=0
  for r in "${REGISTERED[@]:-}"; do
    if [ "$r" = "$t" ]; then found=1; break; fi
  done
  if [ "$found" -eq 0 ]; then UNREGISTERED+=("$t"); fi
done
if [ "${#UNREGISTERED[@]}" -gt 0 ]; then
  say "GATE FAILED: target(s) with no [[bin]] registration in fuzz/Cargo.toml:"
  printf '  - %s\n' "${UNREGISTERED[@]}"
  say "(an unregistered target dies at run time — it must fail here, not be labeled clean)"
  ev "verdict    : RED - unregistered target(s) (no [[bin]] entry in fuzz/Cargo.toml): ${UNREGISTERED[*]}"
  exit 1
fi

ev "cargo-fuzz : $(command -v cargo-fuzz || printf 'ABSENT')"
ev ""
ev "results (exit = cargo fuzz run exit; artifacts = crash artifacts kept):"

crashes=0
failures=0
for t in "${TARGETS[@]}"; do
  say ""
  say "--- $t (${SECS}s)"
  log="$RPT/${t}.log"
  cargo fuzz run "$t" -- -max_total_time="$SECS" -rss_limit_mb=4096 > "$log" 2>&1
  rc=$?
  arts=0
  if [ -d "fuzz/artifacts/$t" ]; then
    arts=$(find "fuzz/artifacts/$t" -type f 2>/dev/null | wc -l | tr -d ' ')
    mkdir -p "$RPT/artifacts-$t"
    cp -r "fuzz/artifacts/$t/." "$RPT/artifacts-$t/" 2>/dev/null || true
  fi
  if [ "$arts" -gt 0 ]; then
    crashes=$((crashes + 1))
    say "CRASH: $arts artifact(s) -> fuzz/artifacts/$t/ (kept in reports)"
    ev "$(printf '%-24s exit=%-3s artifacts=%-3s CRASH' "$t" "$rc" "$arts")"
  elif [ "$rc" -ne 0 ]; then
    failures=$((failures + 1))
    say "FAILED: exit=$rc with no crash artifacts (log: $log)"
    say "(a build failure or instrument error is never 'clean' - W17-A06 F-001)"
    ev "$(printf '%-24s exit=%-3s artifacts=%-3s FAILED (run failure)' "$t" "$rc" "$arts")"
  else
    say "clean"
    ev "$(printf '%-24s exit=%-3s artifacts=%-3s clean' "$t" "$rc" "$arts")"
  fi
done

head1 "campaign result"
say "$crashes crash(es), $failures run failure(s), ${#TARGETS[@]} target(s)"
ev ""
if [ "$crashes" -eq 0 ] && [ "$failures" -eq 0 ]; then
  ev "verdict    : GREEN - all ${#TARGETS[@]} target(s) ran clean (exit=0, no crash artifacts)"
  cp -f "$EVIDENCE" "$RPT/summary.txt" 2>/dev/null || say "WARN: could not mirror the summary into $RPT"
  say "GATE OK: every target ran clean"
  say "written: $EVIDENCE"
  exit 0
fi
ev "verdict    : RED - $crashes crash(es) + $failures run failure(s) of ${#TARGETS[@]} target(s)"
cp -f "$EVIDENCE" "$RPT/summary.txt" 2>/dev/null || say "WARN: could not mirror the summary into $RPT"
say "GATE FAILED: the campaign is red (evidence: $EVIDENCE)"
exit 1
